import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, test } from 'vitest';
import { packageRoot, render, vendoredFromFile } from './licenses.ts';

test('packageRoot finds the package of a bundled module, scoped or not, through pnpm', () => {
  const pnpm = '/r/node_modules/.pnpm/h3@2.0.8/node_modules';
  expect(packageRoot(`${pnpm}/h3/dist/index.mjs`)).toBe(`${pnpm}/h3`);
  expect(packageRoot('/r/node_modules/@huggingface/gguf/dist/index.js')).toBe('/r/node_modules/@huggingface/gguf');
  expect(packageRoot('/r/app/server/lib/http.ts')).toBeNull();
  expect(packageRoot('/r/node_modules/@scope')).toBeNull();
});

test('render sorts by name and says when a package ships no license file', () => {
  const text = render([
    { name: 'zod', version: '4.0.0', license: 'MIT', text: 'MIT License' },
    { name: 'h3', version: '2.0.0', license: 'MIT', text: null },
  ]);
  expect(text.indexOf('## h3 - 2.0.0 (MIT)')).toBeLessThan(text.indexOf('## zod - 4.0.0 (MIT)'));
  expect(text).toContain('No license file; package.json: MIT.');
});

test('vendoredFromFile extracts a vendored package header from a generated module', () => {
  const dir = mkdtempSync(join(tmpdir(), 'lw-lic-'));
  try {
    const file = join(dir, 'httpApiScalar.js');
    writeFileSync(
      file,
      [
        '/* oxlint-disable no-undef *//* Generated by scripts/package-scalar.mjs from @scalar/api-reference 1.81.0 (MIT).',
        ' * Source: https://cdn.jsdelivr.net/npm/@scalar/api-reference@1.81.0/dist/browser/standalone.js',
        ' */export const javascript = "";',
      ].join('\n'),
    );
    expect(vendoredFromFile(file, { name: 'effect', version: '4.1.7' })).toEqual({
      name: '@scalar/api-reference',
      version: '1.81.0',
      license: 'MIT',
      text: 'Vendored in effect 4.1.7 (MIT).\nSource: https://cdn.jsdelivr.net/npm/@scalar/api-reference@1.81.0/dist/browser/standalone.js',
    });

    const plain = join(dir, 'plain.js');
    writeFileSync(plain, 'export const x = 1;\n');
    expect(vendoredFromFile(plain, { name: 'effect', version: '4.1.7' })).toBeNull();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
