/**
 * `THIRD-PARTY-LICENSES.md` next to the server bundle: the license of every npm package bundled into it, from the
 * modules Rolldown reports (`build/server.ts`).
 */
import { closeSync, openSync, readdirSync, readFileSync, readSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Package {
  name: string;
  version: string;
  license: string;
  text: string | null;
}

const VENDORED = /Generated by [^\n]+ from ((?:@[\w.-]+\/)?[\w.-]+) (\S+) \(([^)]+)\)\./;
const VENDORED_SOURCE = /^\s*\*?\s*Source:\s*(\S+)/m;

/** Reads at most the first `bytes` of a file, so multi-megabyte vendored assets are not loaded in full. */
function readHead(file: string, bytes = 512): string {
  const fd = openSync(file, 'r');
  try {
    const buf = Buffer.alloc(bytes);
    const n = readSync(fd, buf, 0, bytes, 0);
    return buf.subarray(0, n).toString('utf8');
  } finally {
    closeSync(fd);
  }
}

/**
 * The license of each upstream bundle that a dependency vendors without its LICENSE file, copied from the upstream
 * repository into `vendored-licenses/` (Scalar's from https://github.com/scalar/scalar/blob/main/LICENSE).
 */
const VENDORED_LICENSES: Readonly<Record<string, string>> = { '@scalar/api-reference': 'scalar-api-reference.txt' };

/** The license text of a vendored bundle; a build that vendors one with no text here fails. */
export function vendoredLicense(name: string): string {
  const file = VENDORED_LICENSES[name];
  if (!file)
    throw new Error(`licenses: no license text for the vendored ${name} (add it to app/build/vendored-licenses/)`);
  return readFileSync(join(import.meta.dirname, 'vendored-licenses', file), 'utf8').trim();
}

/**
 * The packages a bundle names in the license comments it keeps (`/*! name version` then `@license`, or
 * `/*! name vX | MIT License`), as `name version (license)`. The source is the module as written, where the bundle is
 * a JS string: its line breaks are the two characters `\n`.
 */
export function embeddedPackages(source: string): string[] {
  const found = new Set<string>();
  const banner = /\/\*\*?!?\\n\* ((?:@[\w.-]+\/)?[\w.-]+) v?(\d[\w.-]*)\\n(?:\*[^\\]*\\n)*?\* @license ([\w.-]+)/g;
  const inline = /\/\*! ((?:@[\w.-]+\/)?[\w.-]+) v(\d[\w.-]*) \| ([\w.-]+) License/g;
  for (const pattern of [banner, inline]) {
    for (const [, name, version, license] of source.matchAll(pattern)) found.add(`${name} ${version} (${license})`);
  }
  return [...found].toSorted((a, b) => a.localeCompare(b));
}

/**
 * The entry of a generated module that vendors an upstream bundle (Effect's bundled `@scalar/api-reference`
 * script): the bundle's license text, where it comes from, and the packages it embeds with their license comments.
 */
export function vendoredFromFile(file: string, parent: { name: string; version: string }): Package | null {
  let head: string;
  try {
    head = readHead(file);
  } catch {
    return null;
  }
  const match = VENDORED.exec(head);
  if (!match) return null;
  const [, name, version, license] = match;
  if (!name || !version || !license) return null;
  const source = VENDORED_SOURCE.exec(head)?.[1];
  const lines = [vendoredLicense(name), '', `Vendored in ${parent.name} ${parent.version} (${license}).`];
  if (source) lines.push(`Source: ${source}`);
  const embedded = embeddedPackages(readFileSync(file, 'utf8'));
  if (embedded.length > 0) {
    lines.push('', `The bundle embeds these packages and keeps their license comments: ${embedded.join(', ')}.`);
  }
  return { name, version, license, text: lines.join('\n') };
}

/** `/x/node_modules/.pnpm/a@1/node_modules/@s/b/dist/i.js` → `/x/…/node_modules/@s/b`; null outside node_modules. */
export function packageRoot(id: string): string | null {
  const at = id.lastIndexOf('/node_modules/');
  if (at < 0) return null;
  const rest = id.slice(at + '/node_modules/'.length).split('/');
  const depth = rest[0]?.startsWith('@') ? 2 : 1;
  return rest.length > depth ? id.slice(0, at + '/node_modules/'.length) + rest.slice(0, depth).join('/') : null;
}

/** A field of a parsed `package.json`, read as it is written. */
function field(pkg: unknown, key: string): unknown {
  return typeof pkg === 'object' && pkg !== null ? Reflect.get(pkg, key) : undefined;
}

function read(root: string): Package {
  const pkg: unknown = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const license = field(pkg, 'license');
  const file = readdirSync(root).find((f) => /^(?:licen[cs]e|copying)(?:\.|$)/i.test(f));
  return {
    name: String(field(pkg, 'name')),
    version: String(field(pkg, 'version')),
    license: typeof license === 'string' ? license : 'unknown',
    text: file ? readFileSync(join(root, file), 'utf8').trim() : null,
  };
}

export function render(packages: Package[]): string {
  const sorted = packages.toSorted((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const sections = sorted.map(
    (p) => `## ${p.name} - ${p.version} (${p.license})\n\n${p.text ?? `No license file; package.json: ${p.license}.`}`,
  );
  return `# Licenses\n\nThe server bundles these packages, under these licenses:\n\n${sections.join('\n\n')}\n`;
}

/** Writes `file`: the license of every npm package among `moduleIds` (the modules Rolldown bundled). */
export function writeLicenses(moduleIds: Iterable<string>, file: string): void {
  // One entry per package and version: two copies of the same version are one license.
  const seen = new Map<string, Package>();
  for (const id of moduleIds) {
    const clean = id.replace(/^\0/, '').replace(/\?.*$/s, '');
    const root = packageRoot(clean);
    if (!root) continue;
    const p = read(root);
    seen.set(`${p.name}@${p.version}`, p);
    const vendored = vendoredFromFile(clean, p);
    if (vendored) seen.set(`${vendored.name}@${vendored.version}`, vendored);
  }
  writeFileSync(file, render([...seen.values()]));
}
