/**
 * `server/api.gen.ts`: the route manifest (`ROUTES`, method + path, read by the 405 table) and the `Api` type map the
 * web's client is typed by (`src/lib/api.ts`), from Nitro's own scan of the file routes (`nitro.scannedHandlers`). Each
 * route's response type is its handler's return type (`reply<T>()` → `T`); its body and query types are the route
 * file's `export type Body` and `export type Query`, when it has them.
 *
 * Written in `build:before` (dev start and every build), then in dev on every save under `server/routes/api/`: a
 * changed file at once (Nitro's list stays current), an added or deleted one once Nitro has rescanned, which no hook
 * announces: its scan replaces the `scannedHandlers` array.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import type { Nitro, NitroEventHandler, NitroHooks } from 'nitro/types';
import type { Plugin } from 'vite';

const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;
const RESCAN_POLL_MS = 20;
const RESCAN_WAIT_MS = 2000;

export interface FileRoute {
  method: string;
  path: string;
  /** Relative to `server/`, with `./`. */
  file: string;
  body: boolean;
  query: boolean;
}

/**
 * The API routes of Nitro's scan (`/api…`, with a method, not middleware), sorted by path then method. The scan gives
 * lowercase methods (its type says uppercase): both are taken.
 */
export function apiRoutes(handlers: readonly NitroEventHandler[], serverDir: string): FileRoute[] {
  const out: FileRoute[] = [];
  for (const h of handlers) {
    if (h.middleware || !h.method || !(h.route === '/api' || h.route?.startsWith('/api/'))) continue;
    let src: string;
    try {
      src = readFileSync(h.handler, 'utf8');
    } catch {
      continue; // deleted since the scan
    }
    out.push({
      method: h.method.toUpperCase(),
      path: h.route,
      file: `./${relative(serverDir, h.handler).split(sep).join('/')}`,
      body: /^export type Body\b/m.test(src),
      query: /^export type Query\b/m.test(src),
    });
  }
  const order = (m: string) => METHODS.indexOf(m.toLowerCase() as (typeof METHODS)[number]);
  return out.sort((a, b) => a.path.localeCompare(b.path) || order(a.method) - order(b.method));
}

export function render(routes: FileRoute[]): string {
  const imports = routes.map((r, i) => `import type * as r${i} from '${r.file}';`);
  const manifest = routes.map((r) => `  { method: '${r.method}', path: '${r.path}' },`);
  const types = routes.map((r, i) => {
    const args = [`typeof r${i}.default`, r.body ? `r${i}.Body` : 'never', r.query ? `r${i}.Query` : 'never'];
    return `  '${r.method} ${r.path}': Route<${args.join(', ')}>;`;
  });

  return `// Generated by \`build/apiTypes.ts\` from Nitro's scan of \`server/routes/api/\`: do not edit.
import type { Route } from './lib/apiTypes.ts';
${imports.join('\n')}

export const ROUTES = [
${manifest.join('\n')}
] as const;

export interface Api {
${types.join('\n')}
}
` as const;
}

/** Nitro's `build:before` hook and the Vite plugin whose dev watcher keeps the file current. */
export function apiTypes(): { hooks: Partial<NitroHooks>; plugin: Plugin } {
  let nitro: Nitro | undefined;
  /** Nitro's `serverDir` (absolute, `/` last); none when the project has none. */
  const serverDir = () => nitro?.options.serverDir || undefined;
  const write = () => {
    const dir = serverDir();
    if (!nitro || !dir) return;
    const out = join(dir, 'api.gen.ts');
    const text = render(apiRoutes(nitro.scannedHandlers, dir));
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {}
    // Unchanged: not rewritten (the dev worker would reload for nothing).
    if (text !== current) writeFileSync(out, text);
  };
  const afterRescan = async () => {
    const before = nitro?.scannedHandlers;
    const t0 = performance.now();
    while (nitro?.scannedHandlers === before) {
      if (performance.now() - t0 > RESCAN_WAIT_MS) {
        console.warn('[llama-webui] no route rescan by Nitro within 2 s: api.gen.ts written from the last scan');
        break;
      }
      await sleep(RESCAN_POLL_MS);
    }
    write();
  };
  return {
    hooks: {
      'build:before': (n) => {
        nitro = n;
        write();
      },
    },
    plugin: {
      name: 'llama-webui:api-types',
      configureServer(server) {
        server.watcher.on('all', async (event, file) => {
          const dir = serverDir();
          if (!dir || !file.startsWith(join(dir, 'routes/api') + sep)) return;
          if (event === 'change') write();
          else if (event === 'add' || event === 'unlink') await afterRescan();
        });
      },
    },
  };
}
