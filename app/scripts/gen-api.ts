/**
 * Writes `server/api.gen.ts` from the file routes under `server/routes/api/`: the route manifest (`ROUTES`, method +
 * path, read by the 405 table) and the `Api` type map the web's client is typed by (`src/lib/api.ts`). Each route's
 * response type is its handler's return type (`reply<T>()` → `T`); its body and query types are the route file's
 * `export type Body` and `export type Query`, when it has them.
 *
 *   node scripts/gen-api.ts           write the file
 *   node scripts/gen-api.ts --check   fail if it is not up to date
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { parseArgs } from 'node:util';

const APP = join(import.meta.dirname, '..');
const ROUTES_DIR = join(APP, 'server/routes/api');
export const OUT = join(APP, 'server/api.gen.ts');

const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;

export interface FileRoute {
  method: string;
  path: string;
  /** Relative to `server/`, with `./`. */
  file: string;
  body: boolean;
  query: boolean;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? walk(join(dir, e.name))
      : e.name.endsWith('.ts') && !e.name.endsWith('.test.ts')
        ? [join(dir, e.name)]
        : [],
  );
}

/** `profiles/[id]/index.get.ts` → `GET /api/profiles/:id`; null for a file without a method suffix. */
export function routeOf(rel: string): { method: string; path: string } | null {
  const m = /^(.*)\.(get|post|put|patch|delete)\.ts$/.exec(rel.split(sep).join('/'));
  if (!m) return null;
  const segments = (m[1] as string).split('/').filter((s, i, all) => !(s === 'index' && i === all.length - 1));
  const path = ['/api', ...segments.map((s) => s.replace(/^\[(\w+)\]$/, ':$1'))].join('/');
  return { method: (m[2] as string).toUpperCase(), path: path === '/api/' ? '/api' : path };
}

export function scan(): FileRoute[] {
  const out: FileRoute[] = [];
  for (const abs of walk(ROUTES_DIR)) {
    const r = routeOf(relative(ROUTES_DIR, abs));
    if (!r) continue;
    const src = readFileSync(abs, 'utf8');
    out.push({
      ...r,
      file: `./${relative(join(APP, 'server'), abs).split(sep).join('/')}`,
      body: /^export type Body\b/m.test(src),
      query: /^export type Query\b/m.test(src),
    });
  }
  const order = (m: string) => METHODS.indexOf(m.toLowerCase() as (typeof METHODS)[number]);
  return out.sort((a, b) => a.path.localeCompare(b.path) || order(a.method) - order(b.method));
}

export function render(routes: FileRoute[]): string {
  const imports = routes.map((r, i) => `import type * as r${i} from '${r.file}';`);
  const manifest = routes.map((r) => `  { method: '${r.method}', path: '${r.path}' },`);
  const types = routes.map((r, i) => {
    const args = [`typeof r${i}.default`, r.body ? `r${i}.Body` : 'never', r.query ? `r${i}.Query` : 'never'];
    return `  '${r.method} ${r.path}': Route<${args.join(', ')}>;`;
  });
  return [
    '// Generated by `node scripts/gen-api.ts` from `server/routes/api/`: do not edit.',
    "import type { Route } from './lib/apiTypes.ts';",
    ...imports,
    '',
    'export const ROUTES = [',
    ...manifest,
    '] as const;',
    '',
    'export interface Api {',
    ...types,
    '}',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
  const text = render(scan());
  if (values.check) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {}
    if (current !== text) {
      console.error('server/api.gen.ts is out of date: run `node scripts/gen-api.ts`');
      process.exit(1);
    }
  } else writeFileSync(OUT, text);
}
